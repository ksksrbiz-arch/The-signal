          '<p style="font:600 14px/1.5 -apple-system,BlinkMacSystemFont,Segoe UI,Roboto,Helvetica,Arial,sans-serif;margin:0;"><a href="', escapeAttr(permalink), '" style="color:#111;">', escapeHtml(permalink), '</a></p>',
        '</td></tr>',
      '</table>',
      '<p style="max-width:640px;margin:16px auto 0 auto;font:400 12px/1.5 -apple-system,BlinkMacSystemFont,Segoe UI,Roboto,Helvetica,Arial,sans-serif;color:#888;text-align:center;">You subscribed to The Signal at ', escapeHtml(SITE_URL), '. {$unsubscribe}</p>',
